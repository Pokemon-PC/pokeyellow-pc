/* Game Boy / Game Boy Color runtime for statically recompiled games. */
#pragma once
#include <stdint.h>
#include <stddef.h>

typedef struct {
    uint8_t a, b, c, d, e, h, l;
    uint8_t zf, nf, hf, cf;
    uint16_t sp, pc;
    uint8_t ime, halted, stopped;
} CPU;

extern CPU R;
/* CPU clock in T-cycles (4.19 MHz units at normal speed). */
extern uint64_t g_cyc;
/* next cycle at which the hardware must be updated (PPU mode change, ...) */
extern uint64_t g_deadline;

/* memory: 4 KiB pages; NULL = slow path */
extern uint8_t *g_rmap[16];
extern uint8_t *g_wmap[16];
extern uint8_t g_hram[0x100];   /* FF80-FFFE (+ IE at FFFF kept in io) */
uint8_t mem_rd_slow(uint16_t addr);
void mem_wr_slow(uint16_t addr, uint8_t v);
uint8_t io_rd(uint8_t reg);
void io_wr(uint8_t reg, uint8_t v);

static inline uint8_t rd(uint16_t addr) {
    uint8_t *p = g_rmap[addr >> 12];
    return p ? p[addr & 0xFFF] : mem_rd_slow(addr);
}
static inline void wr(uint16_t addr, uint8_t v) {
    uint8_t *p = g_wmap[addr >> 12];
    if (p) p[addr & 0xFFF] = v; else mem_wr_slow(addr, v);
}
static inline uint16_t rd16(uint16_t addr) { return (uint16_t)(rd(addr) | (rd((uint16_t)(addr + 1)) << 8)); }
static inline void wr16(uint16_t addr, uint16_t v) { wr(addr, (uint8_t)v); wr((uint16_t)(addr + 1), v >> 8); }

/* cartridge */
extern uint8_t *g_rom;
extern size_t g_rom_size;
extern unsigned g_rom_bank;      /* current ROMX bank */
extern unsigned g_rom_banks;

/* recompiled code: one function per ROM bank; returns the next pc.
 * g_rc_miss is set when the entry pc was not a known block start. */
typedef uint16_t (*bank_fn)(uint16_t pc);
extern const bank_fn *rc_banks;
extern unsigned rc_nbanks;
extern int g_rc_miss;
/* code the game copies from ROM to RAM (rgbds LOAD blocks), translated too */
typedef struct { uint16_t ram, len; uint32_t rom_off; bank_fn fn; } RamCode;
extern const RamCode *rc_ram;
extern unsigned rc_nram;
extern const char *rc_game_name;
/* one translated ROM (recomp.py output); an executable may hold several
 * (e.g. English and French) and picks the one matching the ROM's CRC */
typedef struct {
    const char *name, *lang;
    uint32_t crc;
    const bank_fn *banks;
    unsigned nbanks;
    const RamCode *ram;
    unsigned nram;
} RcGame;
extern const RcGame *const rc_games[];   /* NULL-terminated, generated by CMake */

/* hardware */
void hw_init(int cgb);
void hw_update(void);            /* catch up PPU/APU/timers to g_cyc, set g_deadline */
void mem_init(void);
void cart_load_save(const char *path);
void cart_flush_save(void);
void ppu_init(void);
void apu_init(int rate);
void apu_catch_up(void);
void apu_write(uint8_t reg, uint8_t v);
uint8_t apu_read(uint8_t reg);
int apu_mix(int16_t *out, int frames); /* host audio thread */

/* interpreter (fallback for code in RAM / unseen addresses) */
void interp_step(void);
extern uint64_t g_interp_count;
void interp_invalid(uint16_t pc, uint8_t op);

/* host */
void host_frame(const uint32_t *fb);  /* called at each VBlank */
uint8_t host_buttons(void);           /* bit0 A,1 B,2 Select,3 Start,4 Right,5 Left,6 Up,7 Down */
void host_log(const char *fmt, ...);
extern int g_quit;

/* I/O registers (FF00-FF7F, FFFF) */
extern uint8_t g_io[0x100];
extern int g_cgb;
extern int g_double_speed;
void request_irq(int bit);

/* save states (tests): each module serializes its own state */
#include <stdio.h>
void st_io(FILE *f, int save, void *p, size_t n);
#define ST(x) st_io(f, save, &(x), sizeof(x))
void mem_state(FILE *f, int save);
void hw_state(FILE *f, int save);
void apu_state(FILE *f, int save);
